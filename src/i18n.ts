const tables: Partial<Record<LangCode, Record<UiKey, string>>> = { en, de };

export type Translate = (key: UiKey, vars?: Record<string, string | number>) => string;

export function translator(lang: LangCode): Translate {
  const table = tables[lang] ?? en;
  return (key, vars) => {
    let text = table[key] ?? en[key];
    if (vars) {
      for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
    }
    return text;
  };
}

export function browserLang(): LangCode {
  return navigator.language?.toLowerCase().startsWith('de') ? 'de' : 'en';
}

